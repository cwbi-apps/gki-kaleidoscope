package net.geoprism.geoai.explorer.web.controller;

import org.springframework.beans.factory.ObjectProvider;
import org.springframework.boot.info.BuildProperties;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.ResponseBody;
import org.springframework.web.bind.annotation.RestController;

import net.geoprism.geoai.explorer.web.model.Version;

@RestController
public class VersionController
{
  // BuildProperties only exists when META-INF/build-info.properties was generated by the
  // spring-boot-maven-plugin, which isn't the case when running straight out of an IDE.
  private final ObjectProvider<BuildProperties> buildProperties;

  public VersionController(ObjectProvider<BuildProperties> buildProperties)
  {
    this.buildProperties = buildProperties;
  }

  @GetMapping("/api/version")
  @ResponseBody
  public ResponseEntity<Version> getVersion()
  {
    BuildProperties properties = this.buildProperties.getIfAvailable();

    if (properties == null)
    {
      return new ResponseEntity<Version>(new Version(), HttpStatus.OK);
    }

    return new ResponseEntity<Version>(new Version(properties.getVersion(), properties.getTime()), HttpStatus.OK);
  }

}
